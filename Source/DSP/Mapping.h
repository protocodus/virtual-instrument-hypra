inline double osc2Semitones (const Osc2Params& p) noexcept
{
    const double fine = std::clamp (p.fine, -50, 50);
    if (p.range <= -25)
        return (fine - 50.0) / 100.0 * 48.0;
    if (p.range >= 25)
        return (fine + 50.0) / 100.0 * 48.0;
    return p.range + fine / 100.0;
}


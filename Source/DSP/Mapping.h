inline Stereo panGains (double panNorm) noexcept
{
    const double pos = std::clamp (panNorm, -1.0, 1.0) * 63.5 + 63.5;
    const auto i = std::min<std::size_t> (static_cast<std::size_t> (pos), 126);
    const double frac = pos - static_cast<double> (i);
    const double l = static_cast<double> (panLeftTable[i])
                     + (static_cast<double> (panLeftTable[i + 1]) - static_cast<double> (panLeftTable[i])) * frac;
    const double r = static_cast<double> (panRightTable[i])
                     + (static_cast<double> (panRightTable[i + 1]) - static_cast<double> (panRightTable[i])) * frac;
    return { l / 32768.0, r / 32768.0 };
}


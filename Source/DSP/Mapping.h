inline double lookupUnsigned (const std::array<std::uint16_t, 128>& table, double unitValue) noexcept
{
    const double pos = std::clamp (unitValue, 0.0, 1.0) * 127.0;
    const auto i = std::min<std::size_t> (static_cast<std::size_t> (pos), 126);
    const double frac = pos - static_cast<double> (i);
    return static_cast<double> (table[i]) + (static_cast<double> (table[i + 1]) - static_cast<double> (table[i])) * frac;
}

inline double superDetuneReg (double knob) noexcept
{
    return (lookupUnsigned (superDetuneTbl, knob) * 0.5 + 2.0) / 32768.0;
}

inline double superDetune (double knob) noexcept
{
    return superDetuneReg (knob) / (642.0 / 32768.0);
}

inline double superMixSide (double mix) noexcept
{
    return (400.0 + 64.0 * std::clamp (mix, 0.0, 1.0) * 127.0) / 32768.0;
}

inline double superCentre (double mix) noexcept
{
    const double m = superMixSide (mix);
    return 0.1953125 * 2.0 * (1.0 - std::min (1.0, 2.1875 * m));
}

inline double superSide (double mix) noexcept
{
    const double m = superMixSide (mix);
    return m * 2.0 * (1.0 - std::min (1.0, 2.1875 * m));
}

inline double pulseWidth (double width) noexcept
{
    return std::min (std::clamp (width, 0.0, 1.0) * 127.0, 124.0) / 128.0;
}

inline double pulseDuty (double width) noexcept
{
    return 0.5 + 0.5 * pulseWidth (width);
}

inline double waveShape (double shape) noexcept
{
    return std::min (std::clamp (shape, 0.0, 1.0) * 127.0, 124.0) / 128.0;
}

inline double triangleModOffset (double offset) noexcept
{
    return std::clamp ((127.0 - std::clamp (offset, 0.0, 1.0) * 127.0) / 128.0, 0.25, 0.890625);
}

inline double triangleModGain (double offset) noexcept
{
    return 1.125 + triangleModOffset (offset);
}

inline double feedbackAmount (double amount) noexcept
{
    const double u = 1.0 - std::clamp (amount, 0.0, 1.0);
    return 1.0 - u * u;
}

inline double feedbackHarmonics (double harmonics) noexcept
{
    return 0.5 * std::clamp (harmonics, 0.0, 1.0);
}

inline double crossModGain (double depth) noexcept
{
    return (51.0 / 128.0) * std::clamp (depth, 0.0, 1.0);
}

// Peak frequency deviation in Hz for a +/-0.5 modulator signal at 88.2 kHz.
inline double crossModHz (double depth) noexcept
{
    return 0.5 * crossModGain (depth) * (0.5 * kEngineRate);
}

inline double cutoffOctaves (int value) noexcept
{
    return std::clamp (value, 0, 127) / 12.0;
}

inline double cutoffCoefficient (double octaves) noexcept
{
    return std::clamp ((5.0 / 128.0) * std::exp2 (octaves - 64.0 / 12.0), 1.0 / 1024.0, 1.0);
}

inline double resonanceBaseQHalf (double resonance) noexcept
{
    return lookupUnsigned (resonanceTable, resonance) / 32768.0;
}

inline double resonanceCutoffBoost (double f) noexcept
{
    constexpr double boostThreshold = 15165.0 / 32768.0;
    constexpr double boostIntercept = 38038.0 / 32768.0;
    return f <= boostThreshold ? (boostIntercept - 0.25 * f) : 1.0;
}

inline double resonanceQHalf (double resonance, double f = 5.0 / 128.0) noexcept
{
    return std::min (0.5, resonanceBaseQHalf (resonance) * resonanceCutoffBoost (f));
}

inline double noiseResonanceQHalf (double resonance, double f = 5.0 / 128.0) noexcept
{
    return resonanceBaseQHalf (resonance) * resonanceCutoffBoost (f);
}

inline double resonanceQ (double resonance, double f = 5.0 / 128.0) noexcept
{
    return 2.0 * resonanceQHalf (resonance, f);
}

inline double resonance12AmpComp (double resonance) noexcept
{
    const int raw = static_cast<int> (std::lround (resonanceBaseQHalf (resonance) * 32768.0));
    const auto idx = static_cast<std::size_t> (std::clamp (raw >> 7, 0, 127));
    return static_cast<double> (res12AmpComp[idx]) / 8192.0;
}


inline double delaySamples (DelayType type, int time) noexcept
{
    const auto idx = static_cast<std::size_t> (std::clamp (time, 0, 127));
    const double base = static_cast<double> (delaySamplesTable[idx]);
    switch (type)
    {
        case DelayType::PanShort: return base * 0.25;
        case DelayType::MonoShort: return base * 0.125;
        case DelayType::PanLR:
        case DelayType::PanRL:
        case DelayType::MonoLong: break;
    }
    return base;
}

inline double delayMaximum (DelayType type) noexcept
{
    return delaySamples (type, 127) / kEngineRate;
}

inline double delaySeconds (DelayType type, int time) noexcept
{
    const double d1 = delaySamples (type, time) / kEngineRate;
    switch (type)
    {
        case DelayType::PanLR:
        case DelayType::PanRL:
        case DelayType::PanShort:
            return 0.5 * d1;
        case DelayType::MonoShort:
        case DelayType::MonoLong:
            break;
    }
    return d1;
}

